import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const sourcePath = path.join(root, "app/shared.css");
const outputPath = path.join(root, "miniapp/src/shared-mobile.generated.css");
const selectedMedia = new Set([
  "@media (max-width: 800px)",
  "@media (max-width: 430px)",
  "@media (pointer: coarse)",
]);

function findBlockEnd(css, openBrace) {
  let depth = 1;
  let quote = "";
  let inComment = false;
  for (let i = openBrace + 1; i < css.length; i += 1) {
    const ch = css[i];
    const next = css[i + 1];
    if (inComment) {
      if (ch === "*" && next === "/") { inComment = false; i += 1; }
      continue;
    }
    if (!quote && ch === "/" && next === "*") { inComment = true; i += 1; continue; }
    if (quote) {
      if (ch === "\\") { i += 1; continue; }
      if (ch === quote) quote = "";
      continue;
    }
    if (ch === '"' || ch === "'") { quote = ch; continue; }
    if (ch === "{") depth += 1;
    if (ch === "}") depth -= 1;
    if (depth === 0) return i;
  }
  throw new Error(`Unclosed CSS block after offset ${openBrace}`);
}

const css = await readFile(sourcePath, "utf8");
const chunks = [];
let cursor = 0;
while (cursor < css.length) {
  const start = css.indexOf("@media", cursor);
  if (start < 0) break;
  const openBrace = css.indexOf("{", start);
  if (openBrace < 0) break;
  const header = css.slice(start, openBrace).trim().replace(/\s+/g, " ");
  const end = findBlockEnd(css, openBrace);
  if (selectedMedia.has(header)) {
    chunks.push(`/* ${header} — 小程序端强制采用网页移动布局 */\n${css.slice(openBrace + 1, end).trim()}`);
  }
  cursor = end + 1;
}

const output = [
  "/* AUTO-GENERATED by scripts/sync-miniapp-mobile-css.mjs. DO NOT EDIT. */",
  "/* Taro plugin-html 对媒体查询兼容有限，因此将网页端手机规则展开后复用。 */",
  "",
  ...chunks,
].join("\n\n") + "\n";
await writeFile(outputPath, output);
console.log(`Synced ${chunks.length} mobile CSS blocks -> ${path.relative(root, outputPath)}`);
